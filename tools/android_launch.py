"""Give the stock Godot APK an app-owned, full-screen Android launch cover."""
from pathlib import Path
import hashlib
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET

ANDROID = "{http://schemas.android.com/apk/res/android}"
APPLICATION_CLASS = "com.graffitty.launch.GraffittyApplication"
ET.register_namespace("android", ANDROID[1:-1])


def prepare_launch_template(source: Path, work: Path) -> Path:
    # Cache resource rebuilding independently of the frequently edited Java bridge.
    digest = hashlib.sha256(source.read_bytes() + Path(__file__).read_bytes()).hexdigest()
    output = work / "launch-template.apk"
    stamp = work / "launch-template.sha256"
    cached_manifest = work / "launch-template/AndroidManifest.xml"
    if output.exists() and stamp.exists() and stamp.read_text() == digest and cached_manifest.exists():
        application = ET.parse(cached_manifest).getroot().find("application")
        # A source edit during a build can stamp a template generated by the
        # already-imported module. Never reuse a different Application class.
        if application is not None and application.get(ANDROID + "name") == APPLICATION_CLASS:
            return output
    apktool = shutil.which("apktool")
    if not apktool:
        raise RuntimeError("apktool is required for the Android launch screen (brew install apktool)")
    decoded = work / "launch-template"
    subprocess.run([apktool, "d", "-s", "-f", "-o", str(decoded), str(source)], check=True)
    # apktool normalizes mipmap-hdpi-v4 to mipmap-hdpi. Godot replaces only
    # its original paths, so these renamed density variants would retain the
    # engine logo and solid background and override the exported base artwork.
    #
    # Keep one base image per icon; Android scales the exported artwork.
    for density in ("ldpi", "mdpi", "tvdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"):
        for directory in (decoded / "res").glob("mipmap-" + density + "*"):
            for name in ("icon", "icon_background", "icon_foreground", "icon_monochrome"):
                for image in directory.glob(name + ".*"):
                    image.unlink()
    # Dictation captures through AAudio, which Android 8 introduced; the
    # client disables Godot's audio driver, its only older capture path.
    sdk_info = decoded / "apktool.yml"
    text, count = re.subn(r"(?m)^([ \t]*minSdkVersion:[ \t]*)'?\d+'?[ \t]*$", r"\g<1>26", sdk_info.read_text())
    if count != 1:
        raise RuntimeError("Expected one minSdkVersion in the decoded template")
    sdk_info.write_text(text)
    manifest_path = decoded / "AndroidManifest.xml"
    manifest = ET.parse(manifest_path)
    application = manifest.getroot().find("application")
    if application is None or application.get(ANDROID + "name"):
        raise RuntimeError("Expected a stock Godot template with no custom Application")
    application.set(ANDROID + "name", APPLICATION_CLASS)
    manifest.write(manifest_path, encoding="utf-8", xml_declaration=True)
    # The window can become visible before the renderer or its UI overlay.
    # Give that earliest frame the same artwork as the native launch cover.
    (decoded / "res/drawable/graffitty_launch.xml").write_text("""<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item><bitmap android:src="@mipmap/icon_background" android:gravity="fill" /></item>
    <item android:width="288dp" android:height="288dp" android:gravity="center">
        <bitmap android:src="@drawable/splash_icon" android:gravity="fill" />
    </item>
</layer-list>
""")
    found = False
    for path in (decoded / "res").glob("values*/styles.xml"):
        styles = ET.parse(path)
        changed = False
        for style in styles.getroot().findall("style"):
            if style.get("name") not in {"GodotAppSplashTheme", "GodotAppMainTheme"}:
                continue
            ET.SubElement(style, "item", name="android:windowBackground").text = "@drawable/graffitty_launch"
            changed = True
            if style.get("name") != "GodotAppSplashTheme":
                continue
            # A launcher can force the system splash despite
            # windowDisablePreview. A translucent launch theme has no opaque
            # system starting surface; The native bridge restores activity
            # opacity after the first frame.
            #
            # Older Android uses its ordinary preview without this API 31+
            # theme.
            if path.parent.name == "values-v31":
                for item in style.findall("item"):
                    if item.get("name") == "android:windowIsTranslucent":
                        item.text = "true"
                        break
                else:
                    ET.SubElement(style, "item", name="android:windowIsTranslucent").text = "true"
            # Android 12+ accepts only a color for its system splash background.
            # Suppress that icon-only preview; our native view draws the wallpaper
            # while the engine loads, until Godot's first application frame.
            ET.SubElement(style, "item", name="android:windowDisablePreview").text = "true"
            found = changed = True
        if changed:
            styles.write(path, encoding="utf-8", xml_declaration=True)
    if not found:
        raise RuntimeError("Godot splash theme missing from export template")
    subprocess.run([apktool, "b", str(decoded), "-o", str(output)], check=True)
    stamp.write_text(digest)
    return output
