#!/usr/bin/env python3
"""Vendor ../graffitty.nvim and regenerate the managed filetree's Lua bundle."""

from pathlib import Path
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]
source = ROOT.parent / "graffitty.nvim"
destination = ROOT / "integrations/graffitty.nvim"
if destination.exists():
    for path in destination.rglob("*"):
        if path.is_file() and not (source / path.relative_to(destination)).exists():
            path.unlink()
shutil.copytree(
    source, destination, dirs_exist_ok=True, ignore=shutil.ignore_patterns(".git")
)
modules = {}
for path in sorted((source / "lua").rglob("*.lua")):
    name = (
        str(path.relative_to(source / "lua"))
        .replace("/init.lua", "")
        .replace(".lua", "")
        .replace("/", ".")
    )
    modules[name] = path.read_text()
body = "-- Generated by tools/sync_nvim_integration.py; edit ../graffitty.nvim instead.\nlocal enabled = ...\nlocal modules = {\n"
body += ",\n".join(
    "[" + json.dumps(name) + "] = " + json.dumps(code) for name, code in modules.items()
)
body += """\n}
for name, source in pairs(modules) do
  if not package.loaded[name] then package.preload[name] = assert(loadstring(source, "@" .. name)) end
end
vim.api.nvim_create_autocmd("VimEnter", { once = true, callback = function()
  if enabled then
    require("graffitty").setup({})
    local nav = require("graffitty.navigator")
    for key, move in pairs({ h = nav.move_left, j = nav.move_down, k = nav.move_up, l = nav.move_right }) do
      vim.keymap.set("n", "<C-" .. key .. ">", move, { silent = true, desc = "Graffitty navigation" })
    end
  end
end })
"""
(ROOT / "apps/server/filetree/integrations.lua").write_text(body)
